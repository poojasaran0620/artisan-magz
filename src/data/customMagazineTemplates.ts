export type CustomOccasionId = 'birthday' | 'couple' | 'friends' | 'wedding' | 'travel' | 'just-because';

export interface OccasionOption {
  id: CustomOccasionId;
  name: string;
  tagline: string;
  description: string;
  badge?: string;
  accentColor: string;
  frontCoverImage: string;
  backCoverImage: string;
  frontCoverTitle: string;
  frontCoverSubtitle: string;
}

export interface MagazinePackage {
  id: string;
  name: string;
  totalPages: number;
  price: number;
  originalPrice: number;
  spreadsCount: number;
  description: string;
  badge?: string;
}

export interface SpreadTemplate {
  id: string;
  occasionId: CustomOccasionId;
  spreadNumber: number;
  name: string;
  subtitle: string;
  leftPageTitle: string;
  rightPageTitle: string;
  leftPageDescription: string;
  rightPageDescription: string;
  leftPageImage: string;
  rightPageImage: string;
  tags: string[];
}

export interface CustomAddOn {
  id: 'none' | 'gift-box' | 'handwritten-letter' | 'combo';
  name: string;
  price: number;
  originalPrice?: number;
  badge?: string;
  description: string;
  benefits: string[];
}

export function calculateSpreadsCount(pages: number): number {
  return Math.max(0, Math.floor((pages - 2) / 2));
}

